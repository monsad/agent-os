import { reviewDiff } from "./agent.js";
import type { Review } from "./schema.js";

async function readStdin(): Promise<string> {
  const chunks: Buffer[] = [];
  for await (const chunk of process.stdin) chunks.push(chunk as Buffer);
  return Buffer.concat(chunks).toString("utf-8");
}

const VERDICT_ICON = { pass: "✅", warn: "🟡", fail: "🔴" } as const;
const REC: Record<Review["recommendation"], string> = {
  merge: "✅ **merge** — safe to merge",
  fix_first: "🟡 **fix first** — address the findings below",
  needs_discussion: "🔴 **needs discussion** — a human decision is required",
};
const SEV = { critical: "🔴 critical", warning: "🟡 warning", observation: "🔵 observation" } as const;

function toMarkdown(r: Review): string {
  const scorecard = r.scorecard
    .map((s) => `| ${s.dimension.replace(/_/g, " ")} | ${VERDICT_ICON[s.verdict]} ${s.verdict} | ${s.note} |`)
    .join("\n");

  const findings = r.findings.length
    ? r.findings
        .map(
          (f) =>
            `- ${SEV[f.severity]} · impact **${f.impact}**${f.file ? ` · \`${f.file}\`` : ""}\n  - ${f.problem}\n  - 💡 ${f.suggestion}`,
        )
        .join("\n")
    : "_No findings._";

  return `## 🤖 AI code review — \`/10x-impl-review\`

${REC[r.recommendation]}

${r.summary}

### Scorecard
| Dimension | Verdict | Evidence |
|---|---|---|
${scorecard}

### Findings
${findings}

<sub>The agent flags; the human owns the merge. · generated by @agent-os/code-reviewer</sub>`;
}

async function main() {
  const diff = (await readStdin()).trim();
  if (!diff) {
    console.log("## 🤖 AI code review\n\n_No diff to review._");
    return;
  }
  const review = await reviewDiff({ title: process.env.PR_TITLE, body: process.env.PR_BODY, diff });
  console.log(toMarkdown(review));
}

main().catch((err) => {
  console.log(`## 🤖 AI code review\n\n⚠️ Review failed: ${err instanceof Error ? err.message : err}`);
});
